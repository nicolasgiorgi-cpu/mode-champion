def pin(pg, code, sel):
    for c in code: pg.click('%s [data-k="%s"]' % (sel, c)); pg.wait_for_timeout(40)
def visit(pg, h, name, tab, must=None):
    go(pg, h)
    t = main_txt(pg)
    ok = not re.search(r'Un souci|Erreur', t[:200])
    check('%s : s\'affiche' % name, ok, t[:200])
    if tab is not None: check('%s : onglet %s' % (name, tab or '(aucun)'), on_tab(pg) == tab.upper(), on_tab(pg))
    if must: check('%s : « %s »' % (name, must), must.lower() in t.lower(), t[:300])
    check('%s : pas de défilement horizontal' % name, noscroll(pg))
    shot(pg, name)
    return t

