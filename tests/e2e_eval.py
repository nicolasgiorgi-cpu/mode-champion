# Skills v2 (25/10/2026) : l'écran Évaluer unifié (une étoile = liste, un atelier = grille, groupes d'ateliers,
# gardé sur le téléphone puis envoyé, plateau = brille, demandes des enfants) et la demande côté enfant.
# Site de démo (sh tests/mkdemo.sh), puis : python3 tests/e2e_eval.py 390 844   (aussi 1180 820)
import sys, os, re
from playwright.sync_api import sync_playwright
BASE = 'http://localhost:8899/index.html'
OUT = os.environ.get('OUT', '/tmp/eval-shots/')
os.makedirs(OUT, exist_ok=True)
W, H = (int(sys.argv[1]), int(sys.argv[2])) if len(sys.argv) > 2 else (390, 844)
tag = '%dx%d' % (W, H)
res = []; errs = []
def check(n, c, i=''): res.append((n, c)); print(('OK  ' if c else 'BAD ') + n, '' if c else i)
def shot(pg, name, full=True): pg.screenshot(path=OUT + tag + '-' + name + '.png', full_page=full)
def noscroll(pg): return pg.evaluate('document.scrollingElement.scrollWidth <= innerWidth + 1')
def go(pg, h, t=800): pg.goto(BASE + h); pg.wait_for_timeout(t)
def main_txt(pg): return (pg.inner_text('main') if pg.query_selector('main') else '').lower()   # en minuscules : certains titres sont en capitales (CSS)
def pin(pg, code, sel):
    for c in code: pg.click('%s [data-k="%s"]' % (sel, c)); pg.wait_for_timeout(40)
def pick(pg, nom): pg.click('[data-act="adultPick"][data-nom="%s"]' % nom); pg.wait_for_timeout(300)
def kid(pg, nom): return pg.evaluate("MC.app.S.cache.group.joueurs.filter(p=>p.joueur.prenom==='%s')[0]" % nom)
def dock_n(pg): return int(pg.inner_text('#ev_n'))

with sync_playwright() as p:
    b = p.chromium.launch(); ctx = b.new_context(viewport={'width': W, 'height': H}, is_mobile=W < 700, has_touch=True)
    ctx.add_init_script('window.__MC_QUIET = 1')
    pg = ctx.new_page()
    pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.on('console', lambda m: errs.append('console: ' + m.text) if m.type == 'error' and 'favicon' not in m.text and 'Failed to load resource' not in m.text else None)
    go(pg, ''); pg.evaluate('localStorage.clear()'); pg.reload(); pg.wait_for_timeout(700)
    # ======================== ÉDUC ========================
    go(pg, '#/adultes', 500); pg.click('[data-act="adultWho"][data-w="e"]'); pg.wait_for_timeout(300); pick(pg, 'Coach Nico'); pin(pg, '2468', '#adultzone'); pg.wait_for_timeout(1400)
    # la page d'un entraînement : « Après la séance »
    go(pg, '#/educ/evt/sp-demo-e1')
    t = main_txt(pg)
    check('entraînement : « Après la séance »', 'après la séance' in t and 'pendant la séance' not in t)
    go(pg, '#/educ/evt/sp-demo-p2')
    check('plateau : « Faire briller des étoiles »', 'faire briller des étoiles' in main_txt(pg))
    # Évaluer, sur l'entraînement passé (groupes d'ateliers publiés)
    go(pg, '#/educ/skills?evt=sp-demo-e0', 1000)
    t = main_txt(pg)
    check('Évaluer : s\'affiche', 'évaluer' in t and not re.search(r'un souci|erreur', t[:200]), t[:200])
    check('Évaluer : les demandes des enfants (Inès, Léo)', 'demandes des enfants (2)' in t and 'inès' in t and 'léo' in t, t[:600])
    check('Évaluer : le choix des étoiles est replié (une étoile déjà choisie)', pg.query_selector('.evsel') is not None and pg.query_selector('[data-act="evAt"]') is None)
    check('Évaluer : lien vers les demandes en haut', pg.query_selector('[data-act="evVoirDem"]') is not None)
    pg.click('[data-act="evOuvre"]'); pg.wait_for_timeout(400)
    check('Évaluer : 11 ateliers prêts', len(pg.query_selector_all('[data-act="evAt"]')) == 11)
    check('Évaluer : 8 cartes', len(pg.query_selector_all('[data-act="evDom"]')) == 8)
    check('Évaluer : une étoile = la liste', pg.query_selector('.evgrid') is None and len(pg.query_selector_all('.evtog')) >= 1)
    check('pas de défilement horizontal (liste)', noscroll(pg))
    shot(pg, 'v01-evaluer-liste')
    # un atelier prêt : la grille
    pg.click('[data-act="evAt"][data-v="maul"]'); pg.wait_for_timeout(500)
    check('atelier Maul : la grille, 5 colonnes', pg.query_selector('.evgrid') is not None and len(pg.query_selector_all('.evh')) == 5)
    check('atelier choisi : le choix se replie', pg.query_selector('.evsel') is not None and 'atelier · maul' in main_txt(pg))
    grps = pg.query_selector_all('[data-act="evGrp"]')
    check('groupes d\'ateliers : pastilles (Tous + 4)', len(grps) == 5, len(grps))
    n_tous = len(pg.query_selector_all('.evn'))
    pg.click('[data-act="evGrp"] >> nth=2'); pg.wait_for_timeout(500)
    n_g = len(pg.query_selector_all('.evn'))
    check('un groupe : seulement ses enfants', 0 < n_g < n_tous, (n_g, n_tous))
    check('pas de défilement horizontal (grille)', noscroll(pg))
    # toucher 3 cases : gardées sur le téléphone
    cells = pg.query_selector_all('.evgrid button.evc')
    for k in range(3): cells[k * 5 + (k % 5)].click(); pg.wait_for_timeout(120)
    check('3 cases touchées : 3 étoiles prêtes', dock_n(pg) == 3, dock_n(pg))
    shot(pg, 'v02-atelier-grille')
    cells[0].click(); pg.wait_for_timeout(120)
    check('toucher à nouveau : enlève', dock_n(pg) == 2)
    cells[0].click(); pg.wait_for_timeout(120)
    go(pg, '#/educ/skills?evt=sp-demo-e0', 900)
    check('après rechargement : toujours 3 prêtes (gardées sur le téléphone)', dock_n(pg) == 3 and len(pg.query_selector_all('.evc.on')) == 3)
    q = pg.evaluate("JSON.parse(localStorage.getItem('mc-eval')).q['sp-demo-e0']")
    ids = [x.split('|')[0] for x in q]
    before = sum(len(kid_['etoiles']) for kid_ in pg.evaluate('MC.app.S.cache.group.joueurs'))
    pg.click('#ev_send'); pg.wait_for_timeout(1200)
    after = sum(len(kid_['etoiles']) for kid_ in pg.evaluate('MC.app.S.cache.group.joueurs'))
    check('Envoyer : 3 étoiles données', after == before + 3, (before, after))
    check('Envoyer : plus rien en attente', dock_n(pg) == 0)
    # sur un plateau : les étoiles brillent
    go(pg, '#/educ/skills?evt=sp-demo-p2', 1000)
    t = main_txt(pg)
    check('plateau : « brillent » expliqué', 'brillent' in t)
    pg.click('[data-act="evOuvre"]'); pg.wait_for_timeout(300)
    pg.click('[data-act="evAt"][data-v="passes-course"]'); pg.wait_for_timeout(500)
    g = pg.query_selector('.evgrid button.evc.gagnee')
    check('plateau : une étoile gagnée se touche pour briller', g is not None)
    if g:
        k = g.get_attribute('data-k'); jid, key = k.split('|'); d, e = key.split(':')
        g.click(); pg.wait_for_timeout(150)
        shot(pg, 'v03-plateau-briller')
        pg.click('#ev_send'); pg.wait_for_timeout(1200)
        row = pg.evaluate("MC.app.S.cache.group.joueurs.filter(p=>p.joueur.id==='%s')[0].etoiles.filter(x=>x.domaine==='%s'&&x.etoile==='%s')[0]" % (jid, d, e))
        check('plateau : l\'étoile brille', bool(row and row.get('brille')), row)
        n_same = pg.evaluate("MC.app.S.cache.group.joueurs.filter(p=>p.joueur.id==='%s')[0].etoiles.filter(x=>x.domaine==='%s'&&x.etoile==='%s').length" % (jid, d, e))
        check('plateau : pas de doublon de l\'étoile', n_same == 1, n_same)
    # les demandes : Oui (Léo, maul debout) et Pas vu (Inès)
    go(pg, '#/educ/skills?evt=sp-demo-e0', 900)
    leo = kid(pg, 'Léo'); dl = [x for x in leo['demandes'] if x['statut'] == 'attente'][0]
    pg.click('[data-act="demOui"][data-id="%s"]' % dl['id']); pg.wait_for_timeout(1100)
    leo = kid(pg, 'Léo')
    check('demande Oui : Léo a l\'étoile Maul · Debout', any(x['domaine'] == 'maul' and x['etoile'] == 'debout' for x in leo['etoiles']))
    ines = kid(pg, 'Inès'); di = [x for x in ines['demandes'] if x['statut'] == 'attente'][0]
    pg.click('[data-act="demNon"][data-id="%s"]' % di['id']); pg.wait_for_timeout(1100)
    ines = kid(pg, 'Inès')
    check('demande Pas vu : statut pasvu', [x for x in ines['demandes'] if x['id'] == di['id']][0]['statut'] == 'pasvu')
    check('plus de demande en attente', 'demandes des enfants' not in main_txt(pg))
    # la fiche d'un enfant : compteurs sur 47, brille
    tom = kid(pg, 'Tom')
    go(pg, '#/educ/joueur/%s?t=skills' % tom['joueur']['id'], 900)
    t = main_txt(pg)
    check('fiche : « / 47 étoiles »', '/ 47 étoiles' in t, t[:200])
    check('fiche : une étoile qui brille, avec « Éteindre »', pg.query_selector('[data-act="eteEtoile"]') is not None)
    check('fiche : pas de défilement horizontal', noscroll(pg))
    shot(pg, 'v04-fiche-skills')
    go(pg, '#/educ/skills/passeport', 900)
    check('passeport : 8 colonnes de cartes', len(pg.query_selector_all('.sktable thead th')) == 10)
    shot(pg, 'v05-passeport')
    # ======================== ENFANT (Tom) ========================
    pg.evaluate('MC.app.setAdult(null)'); go(pg, '', 700)
    pg.click('.kidbtn:has-text("TOM")'); pg.wait_for_timeout(300); pin(pg, '2580', '.modal'); pg.wait_for_timeout(1300)
    go(pg, '#/skills', 900)
    t = main_txt(pg)
    check('enfant : 8 cartes', len(pg.query_selector_all('.sk-card')) == 8)
    check('enfant : « / 47 étoiles » et « brillent »', '/ 47 étoiles' in t and 'brillent' in t, t[:300])
    shot(pg, 'v06-enfant-skills')
    go(pg, '#/skills/passe', 900)
    t = main_txt(pg)
    check('carte Passe : Mains en cible brille', 'brille depuis' in t)
    check('carte Passe : « Fait au plateau » pour une étoile gagnée', pg.query_selector('[data-act="skDem"][data-s="briller"]') is not None)
    go(pg, '#/skills/ruck', 900)
    check('carte Ruck : « Pas vu cette fois » (message neutre)', 'pas vu cette fois' in main_txt(pg))
    go(pg, '#/skills/porteur', 900)
    btn = pg.query_selector('[data-act="skDem"][data-s="gagner"]')
    check('carte Porteur : bouton Demander', btn is not None)
    btn.click(); pg.wait_for_timeout(400)
    pg.click('.modal button:has-text("Demander")'); pg.wait_for_timeout(1100)
    t = main_txt(pg)
    check('demande envoyée : visible, un seul bouton', 'demande envoyée' in t and pg.query_selector('[data-act="skDem"]') is None, t[:400])
    shot(pg, 'v07-enfant-demande')
    pg.click('[data-act="skDemAnn"]'); pg.wait_for_timeout(1000)
    check('demande annulée : les boutons reviennent', pg.query_selector('[data-act="skDem"]') is not None)
    check('enfant : pas de défilement horizontal', noscroll(pg))
    b.close()
print('ERREURS JS :', errs if errs else 'aucune')
ok = sum(1 for r in res if r[1]); print('%d/%d OK (%s)' % (ok, len(res), tag))
sys.exit(0 if ok == len(res) and not errs else 1)
