# (v82) Le mode mini matériel bien visible dans le bilan guidé (et « Je tente ») : sur un test qui a une version mini (barre ou
# corde), une ligne dit laquelle est proposée et change de mode d'un toucher (« J'ai une barre » / « Version mini »), avant le
# premier essai seulement ; l'échauffement du bilan le dit aussi. Horloge : jeudi 12/11 (Bilan 1).
# Site de démo (sh tests/mkdemo.sh), puis : python3 tests/e2e_v82.py 390 844 · 1180 820 · 820 1180
import sys, os
from playwright.sync_api import sync_playwright
BASE = os.environ.get('BASE', 'http://localhost:8899/index.html')
W, H = (int(sys.argv[1]), int(sys.argv[2])) if len(sys.argv) > 2 else (390, 844)
res = []; errs = []
def check(n, c, i=''): res.append((n, c)); print(('OK  ' if c else 'BAD ') + n, '' if c else i)
with sync_playwright() as p:
    b = p.chromium.launch(); ctx = b.new_context(viewport={'width': W, 'height': H}, is_mobile=W < 700, has_touch=True); pg = ctx.new_page()
    pg.clock.set_fixed_time('2026-11-12T10:00:00')
    pg.add_init_script('window.__MC_QUIET=1'); pg.on('pageerror', lambda e: errs.append(str(e)))
    ev = pg.evaluate
    noscroll = lambda: ev('document.scrollingElement.scrollWidth <= document.documentElement.clientWidth + 1')
    def modals():
        while pg.query_selector('.modal button'): pg.click('.modal button >> nth=-1'); pg.wait_for_timeout(300)
    def mode(): return ev("MC.app.S.me.joueur.materiel")
    pg.goto(BASE + '#/connexion'); ev('localStorage.clear()'); pg.reload(); pg.wait_for_timeout(700)
    pg.click('.kidbtn:has-text("TOM")'); pg.wait_for_timeout(350)
    for c in '2580': pg.click('[data-k="%s"] >> visible=true' % c); pg.wait_for_timeout(40)
    pg.wait_for_timeout(1500); modals()
    if mode() == 'mini': ev("MC.app.kidCall('updateMe', { materiel: 'complet' }).then(r => MC.app.setMe(r))"); pg.wait_for_timeout(800)

    pg.goto(BASE + '#/bilan/go'); pg.wait_for_timeout(1200)
    check('Échauffement en matériel complet : pas de « mini matériel »', 'MINI MATÉRIEL' not in pg.inner_text('main').upper())
    pg.click('[data-act="brWarmDone"]'); pg.wait_for_timeout(600)
    check('Test 1 (flamant, sans version mini) : pas de ligne de matériel', pg.query_selector('.note.matos') is None)
    for _ in range(9): pg.click('[data-act="brSkip"]'); pg.wait_for_timeout(250)
    m = pg.query_selector('.note.matos')
    check('Test 10, corde en matériel complet : « Pas de corde ? Version mini »', m is not None and 'PAS DE CORDE' in m.inner_text().upper() and 'VERSION MINI' in m.inner_text().upper(), m.inner_text() if m else None)
    pg.click('[data-act="brMatos"]'); pg.wait_for_timeout(80)
    t = pg.inner_text('main').upper(); m = pg.query_selector('.note.matos')
    check('« Version mini » : tout de suite (sans attendre le serveur), la version sans corde', mode() == 'mini' and 'PAR-DESSUS LA LIGNE' in t and 'MINI MATÉRIEL' in t, (mode(), t[:200]))
    check('… la ligne le dit bien : « Mode mini matériel : la version sans corde » et « J\'ai une corde »', m is not None and 'MODE MINI MATÉRIEL' in m.inner_text().upper() and 'SANS CORDE' in m.inner_text().upper() and 'J\'AI UNE CORDE' in m.inner_text().upper(), m.inner_text() if m else None)
    pg.wait_for_timeout(1100)
    check('… et le serveur l\'a gardé', ev("MC.app.S.me.joueur.materiel") == 'mini')
    for essai in (30, 25):
        for _ in range(essai): pg.click('[data-act="brPlus"] >> nth=0')
        if essai == 30: check('Dès le premier compté : plus de ligne de matériel', pg.query_selector('.note.matos') is None)
        pg.wait_for_timeout(200); pg.click('[data-act="brOk"]'); pg.wait_for_timeout(700)
    bv = ev("(function(){var v=MC.bilan.ensure(MC.app.S.me).v;return {c:v.corde,sm:v.sm_corde};})()")
    check('Corde : le meilleur des 2 essais, et sa version mini', bv == {'c': '30', 'sm': '1'}, bv)
    t = pg.inner_text('main').upper(); m = pg.query_selector('.note.matos')
    check('Le repos avant la corde en 1 min : la ligne y est déjà', 'REPOS' in t and m is not None and 'J\'AI UNE CORDE' in m.inner_text().upper(), (t[:160], m.inner_text() if m else None))
    pg.click('[data-act="brMatos"]'); pg.wait_for_timeout(1200)
    t = pg.inner_text('main').upper()
    check('… « J\'ai une corde » pendant le repos : le prochain test redevient la vraie corde', mode() == 'complet' and 'REPOS' in t and 'CORDE : SAUTS EN 1 MINUTE' in t, (mode(), t[:300]))
    check('… pas de défilement de côté', noscroll())
    pg.click('[data-act="brRestSkip"]'); pg.wait_for_timeout(600)
    m = pg.query_selector('.note.matos')
    check('Corde en 1 min, avant le GO : « Pas de corde ? »', m is not None and 'PAS DE CORDE' in m.inner_text().upper(), m.inner_text() if m else None)
    pg.click('[data-act="brGo"]'); pg.wait_for_timeout(800)
    check('Pendant le test : pas de ligne de matériel', pg.query_selector('.note.matos') is None)
    # les tractions (« Refaire » depuis le récapitulatif)
    ev("MC.act.brGoto({ getAttribute: () => '5' })"); pg.wait_for_timeout(600)
    m = pg.query_selector('.note.matos')
    check('Tractions en matériel complet : « Pas de barre ? Version mini »', m is not None and 'PAS DE BARRE' in m.inner_text().upper() and 'VERSION MINI' in m.inner_text().upper(), m.inner_text() if m else None)
    pg.click('[data-act="brMatos"]'); pg.wait_for_timeout(1200)
    t = pg.inner_text('main').upper(); m = pg.query_selector('.note.matos')
    check('« Version mini » : « Tirages élastique », « la version sans barre » et « J\'ai une barre »', mode() == 'mini' and 'TIRAGES' in t and m is not None and 'SANS BARRE' in m.inner_text().upper() and 'J\'AI UNE BARRE' in m.inner_text().upper(), (mode(), t[:200]))
    check('… pas de défilement de côté', noscroll())
    pg.click('[data-act="brMatos"]'); pg.wait_for_timeout(1200)
    t = pg.inner_text('main').upper()
    check('« J\'ai une barre » : matériel complet, la vraie épreuve', mode() == 'complet' and 'TRACTIONS' in t and 'TIRAGES' not in t and 'MINI MATÉRIEL' not in t, (mode(), t[:200]))
    # (relecture) le comptage a commencé : la ligne s'en va, et le mode ne change plus
    pg.click('[data-act="brPlus"] >> nth=0'); pg.wait_for_timeout(300)
    check('Tractions : dès le premier +1, plus de ligne de matériel', pg.query_selector('.note.matos') is None)
    ev("MC.act.brMatos({ getAttribute: () => 'mini', disabled: false })"); pg.wait_for_timeout(600)
    check('… et le mode ne change plus pendant le test', mode() == 'complet' and 'TRACTIONS' in pg.inner_text('main').upper())
    # une valeur faite après un changement garde la version faite
    ev("MC.act.brGoto({ getAttribute: () => '5' })"); pg.wait_for_timeout(600)
    pg.click('[data-act="brMatos"]'); pg.wait_for_timeout(1200)
    for _ in range(12): pg.click('[data-act="brPlus"] >> nth=0')
    pg.wait_for_timeout(200); pg.click('[data-act="brOk"]'); pg.wait_for_timeout(800)
    bv = ev("(function(){var v=MC.bilan.ensure(MC.app.S.me).v;return {t:v.tract,sm:v.sm_tract};})()")
    check('Tirages élastique notés après « Version mini » : la valeur garde la version mini', bv == {'t': '12', 'sm': '1'}, bv)
    # l'échauffement dit le mode mini
    ev("MC.app.kidCall('updateMe', { materiel: 'mini' }).then(r => MC.app.setMe(r))"); pg.wait_for_timeout(800)
    ev("localStorage.removeItem('mc-bilrun')"); ev("Object.keys(localStorage).filter(k => /bilrun|bilguide/.test(k)).forEach(k => localStorage.removeItem(k))")
    pg.goto(BASE + '#/semaine'); pg.wait_for_timeout(500); pg.reload(); pg.wait_for_timeout(1500); modals()
    pg.goto(BASE + '#/bilan/go'); pg.wait_for_timeout(1200)
    k = pg.inner_text('main').upper()
    check('Échauffement en mode mini : « mini matériel » dès le début', pg.query_selector('[data-act="brWarmDone"]') is not None and 'MINI MATÉRIEL' in k, k[:200])
    # « Je tente » (une seule épreuve) : la même ligne
    ev("MC.app.kidCall('updateMe', { materiel: 'complet' }).then(r => MC.app.setMe(r))"); pg.wait_for_timeout(800)
    pg.goto(BASE + '#/tente/tract'); pg.wait_for_timeout(1000)
    m = pg.query_selector('.note.matos')
    check('« Je tente » les tractions, 1er écran : la même ligne', m is not None and 'PAS DE BARRE' in m.inner_text().upper(), m.inner_text() if m else None)
    pg.click('[data-act="brMatos"]'); pg.wait_for_timeout(1200)
    t = pg.inner_text('main').upper()
    check('… « Version mini » : « Tirages élastique » avant même l\'échauffement', mode() == 'mini' and 'TIRAGES' in t, (mode(), t[:200]))
    pg.click('[data-act="tnChaud"]'); pg.wait_for_timeout(1000)
    m = pg.query_selector('.note.matos')
    check('… puis sur l\'écran du test : « Mode mini matériel »', m is not None and 'MODE MINI MATÉRIEL' in m.inner_text().upper(), m.inner_text() if m else None)
    check('… pas de défilement de côté', noscroll())
    b.close()
ok = sum(1 for _, c in res if c)
print('%d/%d' % (ok, len(res)), 'erreurs JS :', errs[:3])
sys.exit(0 if ok == len(res) and not errs else 1)
