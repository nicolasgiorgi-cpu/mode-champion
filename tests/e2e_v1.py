    for i in range(4): pg.click('[data-act="obNext"]'); pg.wait_for_timeout(250)
    t = main_txt(pg)
    check('visite dernier écran : Missions sans Skills', 'Skills' not in t and 'choisir ton poste' in t, t[:500])
    shot(pg, 'k00-visite5')
    pg.evaluate('window.__MC_QUIET = 1'); ctx.add_init_script('window.__MC_QUIET = 1')
