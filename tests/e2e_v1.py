import sys, os, re
from playwright.sync_api import sync_playwright
BASE = os.environ.get('BASE', 'http://localhost:8898/index.html')
OUT = os.environ.get('OUT', '/tmp/v1-shots/')
os.makedirs(OUT, exist_ok=True)
W, H = (int(sys.argv[1]), int(sys.argv[2])) if len(sys.argv) > 2 else (390, 844)
tag = '%dx%d' % (W, H)
res = []; errs = []
def check(n, c, i=''): res.append((n, c)); print(('OK  ' if c else 'BAD ') + n, '' if c else i)
def shot(pg, name, full=False): pg.screenshot(path=OUT + tag + '-' + name + '.png', full_page=full)
def noscroll(pg): return pg.evaluate('document.scrollingElement.scrollWidth <= innerWidth + 1')
def go(pg, h, t=700): pg.goto(BASE + h); pg.wait_for_timeout(t)
def main_txt(pg): return pg.inner_text('main') if pg.query_selector('main') else ''
def tabs(pg): return [a.inner_text().strip().split('\n')[0].upper() for a in pg.query_selector_all('#nav a') if a.is_visible()]
def pin(pg, code, sel):
    for c in code: pg.click('%s [data-k="%s"]' % (sel, c)); pg.wait_for_timeout(40)
def pick(pg, nom): pg.click('[data-act="adultPick"][data-nom="%s"]' % nom); pg.wait_for_timeout(300)
def hash_(pg): return pg.evaluate('location.hash')
def visit(pg, h, name, must=None, absent=()):
    go(pg, h)
    t = main_txt(pg)
    check('%s : s\'affiche' % name, not re.search(r'Un souci|Erreur', t[:200]), t[:200])
    if must: check('%s : « %s »' % (name, must), must.lower() in t.lower(), t[:300])
    for a in absent: check('%s : pas de « %s »' % (name, a), a.lower() not in t.lower(), t[:400])
    check('%s : pas de défilement horizontal' % name, noscroll(pg))
    shot(pg, name)
    return t
def redirige(pg, h, vers, name):
    go(pg, h, 900)
    check('%s : renvoie vers %s' % (name, vers), hash_(pg).split('?')[0] == vers, hash_(pg))
    check('%s : pas d\'écran d\'erreur' % name, 'Un souci' not in main_txt(pg))

