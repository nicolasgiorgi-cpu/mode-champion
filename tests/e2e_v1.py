    check('enfant : 3 onglets Prépa · Missions · Moi', tabs(pg) == ['PRÉPA', 'MISSIONS', 'MOI'], tabs(pg))
    t = visit(pg, '#/semaine', 'k01-semaine', 'Ma semaine')
