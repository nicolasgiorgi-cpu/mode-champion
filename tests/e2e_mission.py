# Mission « Prépare le jeu à 10 » : dans l'onglet Missions, cartes postes, fiche, test, copains, récompense,
# vues parent et éduc. Site de démo servi en local (sh tests/mkdemo.sh), puis : python3 e2e_mission.py 390 844
import sys, os
from playwright.sync_api import sync_playwright
BASE = 'http://localhost:8899/index.html'
OUT = os.environ.get('OUT', '/tmp/mission-shots/')
os.makedirs(OUT, exist_ok=True)
W, H = (int(sys.argv[1]), int(sys.argv[2])) if len(sys.argv) > 2 else (390, 844)
tag = '%dx%d' % (W, H)
res = []; errs = []
def check(n, c, i=''): res.append((n, c)); print(('OK  ' if c else 'BAD ') + n, '' if c else i)
def shot(pg, name): pg.screenshot(path=OUT + tag + '-' + name + '.png', full_page=False)
def full(pg, name): pg.screenshot(path=OUT + tag + '-' + name + '.png', full_page=True)
def pin(pg, code, sel='.modal'):
    for c in code: pg.click('%s [data-k="%s"]' % (sel, c)); pg.wait_for_timeout(40)
def noscroll(pg): return pg.evaluate('document.scrollingElement.scrollWidth <= innerWidth + 1')
def nb(pg): return pg.evaluate("(function(){var a=document.querySelectorAll('#nav a')[1];var n=a&&a.querySelector('.nb');return n?+n.textContent:0})()")
def close_news(pg):
    if pg.query_selector('.modal.sheet-news'):
        pg.click('.modal.sheet-news button[data-i="0"]'); pg.wait_for_timeout(300)
def pick(pg, nom):
    pg.click('[data-act="adultPick"][data-nom="%s"]' % nom); pg.wait_for_timeout(300)
with sync_playwright() as p:
    b = p.chromium.launch(); ctx = b.new_context(viewport={'width': W, 'height': H}, is_mobile=W < 700, has_touch=True); pg = ctx.new_page()
    pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto(BASE); pg.evaluate('localStorage.clear()'); pg.reload(); pg.wait_for_timeout(700)
    pg.click('.kidbtn:has-text("TOM")'); pg.wait_for_timeout(300); pin(pg, '2580'); pg.wait_for_timeout(1200)
    check('nouveauté de la mission à l\'ouverture', pg.query_selector('.modal.sheet-news') is not None and 'jeu à 10' in pg.inner_text('.modal.sheet-news'))
    close_news(pg)
    check('bandeau « Nouveau dans Missions » sur Prépa', pg.query_selector('.nbanner') is not None)
    n0 = nb(pg)
    check('pastille sur l\'onglet Missions', n0 >= 1, n0)
    check('pas de défilement horizontal (semaine)', noscroll(pg))
    shot(pg, 'm01-semaine')
    xp0 = pg.evaluate('MC.app.S.stats.xp')
    pg.click('#nav a >> nth=1'); pg.wait_for_timeout(700)
    check('Missions : jeu à 10 dans « Pour toute l\'équipe »', pg.query_selector('a.mrow[href="#/mission"]') is not None)
    pg.click('a.mrow[href="#/mission"]'); pg.wait_for_timeout(500)
    check('ouvre la mission', '#/mission' in pg.url, pg.url)
    check('mission : Retour vers Missions', pg.get_attribute('.topbar [data-back]', 'href') == '#/missions', pg.get_attribute('.topbar [data-back]', 'href'))
    shot(pg, 'm02-mission')
    pg.click('a[href="#/mission/postes"].btn'); pg.wait_for_timeout(600)
    check('7 cartes + la carte du test', len(pg.query_selector_all('.cp-card')) == 8, len(pg.query_selector_all('.cp-card')))
    check('Valider grisé sans choix', pg.is_disabled('[data-act="msnSavePostes"]'))
    check('pas de défilement horizontal (cartes)', noscroll(pg))
    shot(pg, 'm03-postes'); full(pg, 'm03-postes-full')
    # fiche du centre : choix 1
    pg.click('a.cp-card[href="#/mission/poste/centre"]'); pg.wait_for_timeout(600)
    check('fiche du poste', pg.query_selector('.cp-dtitle') is not None and 'CENTRE' in pg.inner_text('.cp-dtitle').upper())
    check('fiche : vidéos et joueurs', len(pg.query_selector_all('.cp-vid')) >= 1 and len(pg.query_selector_all('.cp-hero')) == 2)
    check('pas de défilement horizontal (fiche)', noscroll(pg))
    shot(pg, 'm04-fiche')
    pg.click('[data-act="msnRank"][data-k="0"]'); pg.wait_for_timeout(400)
    check('centre en choix 1', pg.evaluate("JSON.parse(localStorage.getItem('mc-mission-jeu10')).postes[0]") == 'centre')
    pg.click('[data-act="msnVid"]'); pg.wait_for_timeout(300)
    check('la vidéo se lance dans la fiche', pg.query_selector('.cp-vframe iframe') is not None)
    full(pg, 'm05-fiche-full')
    pg.goto(BASE + '#/mission/poste/ailier'); pg.wait_for_timeout(500)
    pg.click('[data-act="msnRank"][data-k="1"]'); pg.wait_for_timeout(300)
    pg.goto(BASE + '#/mission/postes'); pg.wait_for_timeout(500)
    check('barre : 2 choix', len(pg.query_selector_all('.cp-slot.on')) == 2)
    shot(pg, 'm06-postes-choix')
    # test « Aide-moi à choisir »
    pg.click('a.cp-card[href="#/mission/quiz"]'); pg.wait_for_timeout(500)
    shot(pg, 'm07-quiz')
    for k in range(5):
        pg.click('[data-act="msnQopt"][data-j="0"]'); pg.wait_for_timeout(150)
        if k == 0: pg.click('[data-act="msnQopt"][data-j="1"]'); pg.wait_for_timeout(150)
        pg.click('[data-act="msnQnext"]'); pg.wait_for_timeout(250)
    check('résultat du test : 3 postes', len(pg.query_selector_all('.cp-qres .cp-card')) == 3)
    full(pg, 'm08-quiz-res')
    pg.click('[data-act="msnQkeep"]'); pg.wait_for_timeout(500)
    top = pg.evaluate("JSON.parse(localStorage.getItem('mc-mission-jeu10')).postes")
    check('« Garder ces 3 postes »', len(top) == 3 and '#/mission/postes' in pg.url, top)
    pg.click('[data-act="msnSavePostes"]'); pg.wait_for_timeout(900)
    check('postes enregistrés → copains', '#/mission/copains' in pg.url and pg.evaluate("MC.app.S.me.missions[0].reponses.postes.length") == 3, pg.url)
    check('pas encore de récompense', pg.evaluate('MC.app.S.stats.xp') == xp0)
    shot(pg, 'm09-copains')
    check('copains : pas soi-même', 'TOM' not in pg.inner_text('#coplist').upper())
    check('Terminer grisé sans copain', pg.is_disabled('[data-act="msnCopSave"]'))
    pg.fill('#copq', 'sa'); pg.wait_for_timeout(300)
    check('recherche', len(pg.query_selector_all('#coplist .cop')) == 1, len(pg.query_selector_all('#coplist .cop')))
    pg.click('#coplist .cop'); pg.wait_for_timeout(300)
    pg.fill('#copq', ''); pg.wait_for_timeout(200)
    pg.click('#coplist .cop:has-text("Nina")'); pg.wait_for_timeout(300)
    check('2 copains choisis', len(pg.query_selector_all('.cop-chip')) == 2)
    check('pas de défilement horizontal (copains)', noscroll(pg))
    shot(pg, 'm10-copains-choisis')
    pg.click('[data-act="msnCopSave"]'); pg.wait_for_timeout(1000)
    check('mission accomplie', '#/mission/bravo' in pg.url and pg.evaluate('MC.app.S.me.missions[0].faite'), pg.url)
    xp1 = pg.evaluate('MC.app.S.stats.xp')
    check('+200 XP et +100 XP du badge', xp1 - xp0 == 300, (xp0, xp1))
    check('badge gagné', pg.evaluate('MC.app.S.stats.badges.jeu10.earned'))
    shot(pg, 'm11-bravo')
    pg.click('a.btn[href="#/missions"]'); pg.wait_for_timeout(700)
    check('Missions : le jeu à 10 n\'est plus « en cours »', pg.query_selector('a.mrow[href="#/mission"]') is None)
    check('pastille Missions en baisse', nb(pg) < n0, (n0, nb(pg)))
    pg.goto(BASE + '#/missions?vue=faites'); pg.wait_for_timeout(600)
    check('Missions › Faites : le jeu à 10', pg.query_selector('a.mrow[href="#/mission"]') is not None)
    pg.goto(BASE + '#/profil'); pg.wait_for_timeout(500)
    check('Moi : Mes postes et mes copains', pg.query_selector('a[href="#/mission"]') is not None)
    pg.goto(BASE + '#/trophees'); pg.wait_for_timeout(500)
    check('trophées : famille missions', 'BADGES DE MISSIONS' in pg.inner_text('main').upper())
    pg.goto(BASE + '#/mission'); pg.wait_for_timeout(500); shot(pg, 'm12-mission-faite')
    check('mission : accomplie', 'MISSION ACCOMPLIE' in pg.inner_text('main').upper())
    # --- parent de Tom : l'état de la mission, sans les copains
    pg.evaluate("MC.app.setKid(null)")
    pg.goto(BASE + '#/adultes'); pg.wait_for_timeout(500); pick(pg, 'Tom'); pin(pg,'1357', '#adultzone'); pg.wait_for_timeout(1200)
    if '#/parent/bienvenue' in pg.url:
        for i in range(2): pg.click('[data-act="obNext"]'); pg.wait_for_timeout(300)
        pg.click('[data-act="obShared"][data-v="1"]'); pg.wait_for_timeout(200)
        pg.click('[data-act="obDone"]'); pg.wait_for_timeout(900)
    close_news(pg)
    check('parent : espace parent', '#/parent' in pg.url, pg.url)
    pg.goto(BASE + '#/parent/missions?vue=faites'); pg.wait_for_timeout(700)
    check('parent : jeu à 10 dans les missions faites', pg.query_selector('a.mrow[href="#/parent/missions/jeu10"]') is not None)
    pg.click('a.mrow[href="#/parent/missions/jeu10"]'); pg.wait_for_timeout(600)
    txt = pg.inner_text('main')
    check('parent : mission accomplie et postes', 'ACCOMPLIE' in txt.upper() and 'SES POSTES' in txt.upper(), txt[:300])
    fam = pg.evaluate("JSON.stringify(MC.app.S.cache.family||{})")
    check('parent : aucun copain dans les données', '"copains"' not in fam)
    shot(pg, 'm13-parent')
    # --- éduc
    pg.evaluate("MC.app.setAdult(null)")
    pg.goto(BASE + '#/adultes'); pg.wait_for_timeout(500); pg.click('[data-act="adultWho"][data-w="e"]'); pg.wait_for_timeout(300); pick(pg, 'Coach Nico'); pin(pg,'2468', '#adultzone'); pg.wait_for_timeout(1200)
    if '#/educ/bienvenue' in pg.url:
        for i in range(2): pg.click('[data-act="obNext"]'); pg.wait_for_timeout(300)
        pg.click('[data-act="obPick"] >> nth=0'); pg.wait_for_timeout(200)
        pg.click('[data-act="obEducDone"]'); pg.wait_for_timeout(1000)
    close_news(pg)
    pg.goto(BASE + '#/educ/missions'); pg.wait_for_timeout(700)
    check('Progrès › Missions : lien jeu à 10', pg.query_selector('a[href="#/educ/mission"]') is not None)
    pg.click('a[href="#/educ/mission"]'); pg.wait_for_timeout(700)
    t = pg.inner_text('main').upper()
    check('éduc : vue de la mission', 'POSTES DEMANDÉS' in t and len(pg.query_selector_all('.pbar')) == 7, t[:200])
    check('éduc : pas de joueur Test', 'TEST' not in t)
    check('pas de défilement horizontal (éduc mission)', noscroll(pg))
    full(pg, 'm14-educ-mission')
    pg.click('[data-act="msnImport"]'); pg.wait_for_timeout(600)
    check('reprise du formulaire : message clair en démo', 'serveur Google' in pg.inner_text('#toast'), pg.inner_text('#toast'))
    tid = pg.evaluate("MC.app.S.cache.group.joueurs.find(p=>p.joueur.prenom==='Tom').joueur.id")
    pg.goto(BASE + '#/educ/joueur/' + tid + '?t=terrain'); pg.wait_for_timeout(900)
    t = pg.inner_text('main').upper()
    check('fiche : partie Jeu à 10', 'JEU À 10' in t and 'SES COPAINS' in t, t[:200])
    check('fiche : copain réciproque (Sacha ⇄)', 'SACHA ⇄' in t)
    check('fiche : choisi par Sacha', "L'ONT CHOISI" in t)
    full(pg, 'm15-educ-fiche')
    b.close()
print('ERREURS JS:', errs)
bad = [n for n, c in res if not c]
print('%d/%d OK' % (len(res) - len(bad), len(res)), 'ÉCHECS:', bad)
